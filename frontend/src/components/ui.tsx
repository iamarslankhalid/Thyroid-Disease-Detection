type AlertTone = "error" | "success" | "info" | "warning";

const ALERT_STYLES: Record<AlertTone, { icon: IconName; className: string }> = {
  error: { icon: "alert", className: "border-serious/30 bg-serious-soft text-serious" },
  success: { icon: "checkCircle", className: "border-good/30 bg-good-soft text-good" },
  warning: { icon: "alert", className: "border-warning/30 bg-warning-soft text-warning" },
  info: { icon: "info", className: "border-accent/25 bg-accent-soft text-accent" },
};

export function Alert({ tone, children }: { tone: AlertTone; children: ReactNode }) {
  const style = ALERT_STYLES[tone];
  return (
    <div
      role={tone === "error" ? "alert" : "status"}
      className={`flex items-start gap-3 rounded-xl border px-4 py-3 text-sm ${style.className}`}
    >
      <Icon name={style.icon} className="mt-0.5 h-4 w-4 shrink-0" />
      <div className="min-w-0 text-ink-1">{children}</div>
    </div>
  );
}

